#!/usr/bin/env node
/**
 * Regenerates src/components/charts/index.ts as a barrel over everything the
 * shadcn CLI dropped into that folder. Run after `shadcn add @bklit/...`.
 */
import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const dir = join(root, "src", "components", "charts")

if (!existsSync(dir)) {
  mkdirSync(dir, { recursive: true })
}

const files = readdirSync(dir)
  .filter((f) => /\.(ts|tsx)$/.test(f))
  .filter((f) => f !== "index.ts" && f !== "index.tsx")
  .filter((f) => !f.endsWith(".d.ts"))
  .map((f) => f.replace(/\.tsx?$/, ""))
  .sort()

const body = [
  "// AUTO-GENERATED by scripts/gen-charts-index.mjs — do not edit by hand.",
  "// Re-run: npm run charts:index",
  "",
  ...files.map((f) => `export * from "./${f}"`),
  "",
].join("\n")

writeFileSync(join(dir, "index.ts"), body, "utf8")
console.log(`charts barrel: ${files.length} module(s) exported`)
if (files.length === 0) {
  console.log("  (nothing installed yet — run `npm run charts:add`)")
}
